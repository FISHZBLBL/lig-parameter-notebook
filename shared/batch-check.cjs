'use strict';
const assert = require('node:assert/strict');
require('./batch-core.js');
require('./core.js');
const api = globalThis.LIGBatchCore;
const fixture = { power: 1.5, speed: 100, frequency: 100, spacing: 25, powerMode: 'watts', arrayPercent: null };
assert.deepEqual(api.parseLevels('1:0.1:1.3', '功率'), [1, 1.1, 1.2, 1.3]);
assert.deepEqual(api.parseLevels('1e-3:1e-3:4e-3'), [0.001, 0.002, 0.003, 0.004]);
assert.deepEqual(api.parseLevels('1，2;3；4\n5 1 2.0'), [1, 2, 3, 4, 5]);
assert.equal(api.parseLevels('1:1:1000').length, 1000);
assert.throws(() => api.parseLevels('1:1:1001'), /1000/);
assert.throws(() => api.parseLevels('1:1:1000 1001'), /1000/);
for (const invalid of ['', '0', '-1', 'Infinity', 'NaN', '0x10', '1:0:3', '3:1:1', '1:0.3:2']) assert.throws(() => api.parseLevels(invalid));
const rows = api.fromLevels({ power: '1:1:10', speed: '1:1:10', frequency: '100', spacing: '25' });
assert.equal(rows.length, 100);
assert.deepEqual(rows[0], { power: 1, speed: 1, frequency: 100, spacing: 25, powerMode: 'watts', arrayPercent: null });
assert.equal(api.fromLevels({ power: '1:1:10', speed: '1:1:10', frequency: '1:1:10', spacing: '1' }).length, 1000);
assert.throws(() => api.fromLevels({ power: '1:1:7', speed: '1:1:11', frequency: '1:1:13', spacing: '1' }), /1001组参数组合、7007个样品/);
const fiveLevels = api.fromLevels({ power: '1:1:5', speed: '1:1:5', frequency: '1:1:5', spacing: '1:1:5' });
assert.equal(fiveLevels.length, 625);
assert.equal(api.plan(fiveLevels, []).sampleCount, 4375);
assert.deepEqual(api.fromLevels({ power: ['1', 1, 2], speed: [100], frequency: [100], spacing: [25] }).map(row => row.power), [1, 2]);
const english = 'power_w,speed_mm_s,frequency_khz,spacing_um\r\n1.5,100,100,25\r\n';
assert.deepEqual(api.parseTable(english), [fixture]);
assert.deepEqual(api.parseTable('功率(W)\t扫描速度(mm/s)\t重复频率(kHz)\t线间距(μm)\n1.5\t100\t100\t25'), [fixture]);
assert.deepEqual(api.parseTable('power,speed,frequency,spacing\n"1.5","100","100","25"'), [fixture]);
assert.deepEqual(api.parseTable('\uFEFF1.5\t100\t100\t25'), [fixture]);
assert.deepEqual(api.parseTable('1.5,100,100,25'), [fixture]);
assert.throws(() => api.parseTable('功率(mW),扫描速度(mm/s),重频(kHz),线间距(um)\n1,2,3,4'), /不支持mW/);
assert.throws(() => api.parseTable('speed,power,frequency,spacing\n1,2,3,4'), /不支持换序/);
assert.throws(() => api.parseTable('1,2,3,4\n5,0,7,8'), /第2行扫描速度/);
assert.throws(() => api.parseTable('1,2,3,4\n5,6,7'), /第2行必须有4列/);
assert.throws(() => api.parseTable('1,2,3,4\n\n5,6,7,8'), /第2行必须有4列/);
assert.throws(() => api.parseTable('"1"x,2,3,4'), /引号结束后/);
assert.throws(() => api.parseTable('"1,2,3,4'), /引号未闭合/);
assert.equal(api.parseTable(Array(1000).fill('1,2,3,4').join('\n')).length, 1000);
assert.throws(() => api.parseTable(Array(1001).fill('1,2,3,4').join('\n')), /最多1000行/);
const oneHundred = api.plan(rows, []);
assert.equal(oneHundred.groupCount, 100);
assert.equal(oneHundred.sampleCount, 700);
assert.equal(oneHundred.electricalCount, 500);
assert.equal(oneHundred.characterizationCount, 200);
const duplicated = api.plan([fixture, { ...fixture, power: '1.50' }, { ...fixture, power: 2 }], [{ ...fixture, isDemo: false }]);
assert.equal(duplicated.skippedInput, 1);
assert.equal(duplicated.skippedExisting, 1);
assert.equal(duplicated.groupCount, 1);
assert.equal(api.plan([fixture], [{ ...fixture, isDemo: true }]).groupCount, 1);
assert.equal(api.plan([fixture], [{ ...fixture }]).groupCount, 1);
const deletedGroup = globalThis.LIGCore.createGroup(fixture, []);
deletedGroup.deletedAt = '2026-10-28T04:00:00.000Z';
const replacementPlan = api.plan([fixture], [deletedGroup]);
assert.equal(replacementPlan.groupCount, 1); assert.equal(replacementPlan.skippedExisting, 0);
const replacement = globalThis.LIGCore.createGroup(replacementPlan.rows[0], [deletedGroup]);
assert.equal(replacement.id, 'C002'); assert.equal(deletedGroup.id, 'C001');
assert.throws(() => api.plan([fixture], Array.from({ length: 1000 }, () => ({ ...deletedGroup }))), /当前仅剩0组容量/);
assert.equal(api.plan([fixture, fixture], [{ ...fixture, isDemo: false }], { allowDuplicates: true }).groupCount, 2);
const almostFull = Array.from({ length: 999 }, () => ({ ...fixture, isDemo: true }));
assert.throws(() => api.plan([fixture, { ...fixture, power: 2 }], almostFull), /当前仅剩1组容量/);
assert.equal(api.plan([fixture], almostFull).groupCount, 1);
const overCapacity = [fixture, { ...fixture, power: 2 }];
const originalRows = JSON.stringify(overCapacity), originalExisting = JSON.stringify(almostFull);
assert.throws(() => api.plan(overCapacity, almostFull), /本批未创建/);
assert.equal(JSON.stringify(overCapacity), originalRows);
assert.equal(JSON.stringify(almostFull), originalExisting);
assert.throws(() => api.plan(Array(1001).fill(fixture), [], { allowDuplicates: true }), /1—1000行/);
const source = [{ ...fixture }], existing = [{ ...fixture, isDemo: true }];
const prepared = api.plan(source, existing);
prepared.rows[0].power = 99;
assert.equal(source[0].power, 1.5);
assert.equal(existing[0].power, 1.5);
assert.throws(() => api.plan([{ ...fixture, spacing: '' }], []), /第1行线间距/);
const percentLaser = api.fromLevels({ power: '20,30', speed: '100', frequency: '100', spacing: '25' }, { powerMode: 'percent', arrayPercent: 60 });
assert.deepEqual(percentLaser.map(row => [row.powerMode, row.power, row.arrayPercent]), [['percent', 20, 60], ['percent', 30, 60]]);
const percentArray = api.fromLevels({ power: '20,30', speed: '100', frequency: '100', spacing: '25' }, { powerMode: 'percent', inputPower: 'array', laserPercent: 80 });
assert.deepEqual(percentArray.map(row => [row.powerMode, row.power, row.arrayPercent]), [['percent', 80, 20], ['percent', 80, 30]]);
assert.equal(api.fromLevels({ power: '20', speed: '100', frequency: '100', spacing: '25' }, { powerMode: 'percent' })[0].arrayPercent, 100);
assert.throws(() => api.fromLevels({ power: '101', speed: '100', frequency: '100', spacing: '25' }, { powerMode: 'percent' }), /不超过100/);
assert.throws(() => api.fromLevels({ power: '20', speed: '100', frequency: '100', spacing: '25' }, { powerMode: 'percent', inputPower: 'array' }), /基准激光器/);
const laserTable = api.parseTable('laser_percent,speed_mm_s,frequency_khz,spacing_um\n20,100,100,25', { powerMode: 'percent', arrayPercent: 60 });
assert.deepEqual(laserTable, [percentLaser[0]]);
const arrayTable = api.parseTable('阵列(%),扫描速度(mm/s),重频(kHz),线间距(um)\n20,100,100,25', { powerMode: 'percent', inputPower: 'array', laserPercent: 80 });
assert.deepEqual(arrayTable, [percentArray[0]]);
const fiveCSV = 'laser_percent,array_percent,speed_mm_s,frequency_khz,spacing_um\n20,60,100,100,25\n30,60,100,100,25';
assert.deepEqual(api.parseTable(fiveCSV, { powerMode: 'percent' }), percentLaser);
assert.throws(() => api.parseTable(fiveCSV), /须先选择/);
assert.throws(() => api.parseTable(english, { powerMode: 'percent' }), /口径不一致/);
assert.throws(() => api.parseTable('laser_percent,speed_mm_s,frequency_khz,spacing_um\n20,100,100,25'), /口径不一致/);
assert.throws(() => api.parseTable(fiveCSV.replace('20,60', '20,101'), { powerMode: 'percent' }), /不超过100/);
const threeModes = [{ ...fixture, power: 20 }, percentLaser[0], { ...percentLaser[0], arrayPercent: 50 }];
assert.equal(api.plan(threeModes, []).groupCount, 3);
assert.equal(api.plan([percentLaser[0]], [{ ...percentLaser[0], isDemo: false }]).skippedExisting, 1);
assert.equal(api.plan([percentLaser[0]], [{ ...percentLaser[0], arrayPercent: 50, isDemo: false }]).groupCount, 1);
assert.equal(api.plan([{ power: 1.5, speed: 100, frequency: 100, spacing: 25 }], [{ ...fixture, isDemo: false }]).skippedExisting, 1);
assert.equal(api.plan([percentLaser[0]], []).rows[0].powerMode, 'percent');
console.log('PASS: percent laser/array and watts plans, dynamic four/five-column tables and roundtrip, mode-aware dedupe, deleted-group replacement without ID reuse, tombstones counted in capacity, exact ranges, 625 groups, capacity and original validation checks.');
